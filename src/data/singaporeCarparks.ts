/**
 * Computes great-circle distance in kilometers using the Haversine formula
 */
export function calculateDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

/**
 * Returns occupancy status category
 */
export function getAvailabilityStatus(available: number, total: number): {
  status: 'available' | 'limited' | 'full';
  label: string;
  badgeBg: string;
  badgeText: string;
  colorHex: string;
  percentage: number;
} {
  const percentage = total > 0 ? Math.round((available / total) * 100) : 0;

  if (available <= 5 || percentage <= 10) {
    return {
      status: 'full',
      label: available === 0 ? 'Full' : 'Nearly Full',
      badgeBg: 'bg-rose-50 border-rose-200',
      badgeText: 'text-rose-700',
      colorHex: '#e11d48',
      percentage,
    };
  }
  if (percentage <= 30 || available <= 30) {
    return {
      status: 'limited',
      label: 'Limited Lots',
      badgeBg: 'bg-amber-50 border-amber-200',
      badgeText: 'text-amber-700',
      colorHex: '#d97706',
      percentage,
    };
  }
  return {
    status: 'available',
    label: 'Available',
    badgeBg: 'bg-emerald-50 border-emerald-200',
    badgeText: 'text-emerald-700',
    colorHex: '#059669',
    percentage,
  };
}
